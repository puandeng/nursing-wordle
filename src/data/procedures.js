export function getRandomProcedure(excludeId) {
  const pool = PROCEDURES.filter(p => p.id !== excludeId);
  return pool[Math.floor(Math.random() * pool.length)];
}

export function shuffleSteps(steps) {
  const arr = steps.map((text, correctIndex) => ({ text, correctIndex }));
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

export function checkOrder(arranged) {
  return arranged.every((step, i) => step.correctIndex === i);
}

export function countCorrect(arranged) {
  return arranged.filter((step, i) => step.correctIndex === i).length;
}
