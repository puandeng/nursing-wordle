/**
 * Get today's puzzle using a deterministic index based on the date.
 * Cycles through puzzles, so the game can run indefinitely.
 */
export function getDailyPuzzle() {
  const today = new Date();
  const epoch = new Date(2024, 0, 1); // Jan 1, 2024
  const daysSinceEpoch = Math.floor((today - epoch) / (1000 * 60 * 60 * 24));
  const idx = daysSinceEpoch % PUZZLES.length;
  return { ...PUZZLES[idx], puzzleNumber: daysSinceEpoch + 1 };
}

export function getPuzzleByIndex(idx) {
  return PUZZLES[idx % PUZZLES.length];
}

